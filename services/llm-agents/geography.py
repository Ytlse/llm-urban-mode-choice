"""
Geographic constants for the Toulouse simulation area.

TOULOUSE_OSM_ROUTES_30K_BBOX is the largest axis-aligned rectangle fully
inscribed within the convex hull of all OSMnx drive-mode road edges within
30 km of Toulouse city centre — every point in this rectangle is reachable
by car through that graph.

How the convex hull was computed:

    import osmnx as ox
    import geopandas as gpd

    G = ox.graph_from_address("Toulouse, France", dist=30_000, network_type="drive")
    gdf_edges = ox.graph_to_gdfs(G, nodes=False, edges=True)
    hull = gdf_edges.unary_union.convex_hull          # Shapely polygon
    gdf  = gpd.GeoDataFrame(geometry=[hull], crs="EPSG:4326")
    gdf["source"] = "Routes OSM (30km)"

The inscribed rectangle was then read from the otp_shape.ipynb notebook.

TOULOUSE_TRANSIT_SERVICE_WKT is the CONCAVE hull of the GTFS stop coordinates that OTP's
street graph can reach — every Tisséo stop, plus the TER stops inside the perimeter polygon.
It describes where transit service exists; it is **not** a routing guard. Recipe:
scripts/data/gtfs/transit_service_hull.py (was: scripts/general/otp_shape.ipynb).

⚠ It used to be described here as a pre-flight guard against OTP's "Couldn't link" error.
That has not been true since the 2026-09-03 port: OTP's street graph now covers the whole
perimeter polygon, so a point outside this hull links fine — it is merely far from any stop.
Measured on the v4 sealed population (2 580 homes and activity places): 0 "Couldn't link".
The only reader of this constant is vizpop.py.

⚠ Since 2026-09-03 (ticket 031, part 2), the simulation scope is no longer a
disk nor a rectangle: it is the **polygon of the 453 communes** of the EMC² 2023 survey
(`mobility_core/data/couronne_perimetre.geojson`, table `commune_couronne.json`). Loading
filters by home commune (`inputs/population/perimeter.py`), the OSMnx graph served at
runtime is the polygon's (`PERIMETER_CACHE_KEY`), and `TOULOUSE_CENTER_DIST_M` /
`TOULOUSE_OSM_ROUTES_30K_BBOX` only keep an AUDIT role: identifying the historical
30 km graph (`PRODUCTION_CACHE_KEY_30KM`) and measuring what the rectangle excluded.
"""

